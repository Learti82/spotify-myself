import "server-only";
import { createClient, type SupabaseClient } from "@supabase/supabase-js";

/**
 * Server-only Supabase client. The service-role key never reaches the browser;
 * every request is first gated by the owner's passcode session in proxy.ts.
 */
let client: SupabaseClient | null = null;

export const BUCKET = process.env.SUPABASE_BUCKET || "music";

export function cloudConfigured(): boolean {
  return Boolean(process.env.SUPABASE_URL && process.env.SUPABASE_SERVICE_ROLE_KEY);
}

export function supabaseAdmin(): SupabaseClient {
  if (!cloudConfigured()) throw new Error("Cloud storage is not configured.");
  client ??= createClient(process.env.SUPABASE_URL!, process.env.SUPABASE_SERVICE_ROLE_KEY!, {
    auth: { persistSession: false, autoRefreshToken: false },
  });
  return client;
}

/** Storage paths are always generated by the server; reject anything else. */
export function isSafeStoragePath(path: unknown): path is string {
  return typeof path === "string" && /^songs\/[0-9a-f-]{36}\/[A-Za-z0-9._-]{1,120}$/.test(path);
}
